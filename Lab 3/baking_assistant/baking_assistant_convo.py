def decode_audio(audio_bytes):
    # this function was generated by chatGPT
    """Convert webm/opus to PCM WAV using ffmpeg."""
    process = subprocess.Popen(
        ["ffmpeg", "-i", "pipe:0", "-ar", "16000", "-ac", "1", "-f", "s16le", "pipe:1"],
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
    )
    pcm_data, _ = process.communicate(audio_bytes)
    return pcm_data

def get_recipe_from_url(url):
    # this function was generated by chatGPT
    response = requests.get(url)
    response.raise_for_status()
    soup = BeautifulSoup(response.text, "html.parser")

    # --- INGREDIENTS ---
    ingredients = []
    for li in soup.find_all("li", class_="wprm-recipe-ingredient"):
        amount = li.find("span", class_="wprm-recipe-ingredient-amount")
        unit = li.find("span", class_="wprm-recipe-ingredient-unit")
        name = li.find("span", class_="wprm-recipe-ingredient-name")

        ingredient_text = " ".join(
            filter(None, [
                amount.get_text(strip=True) if amount else None,
                unit.get_text(strip=True) if unit else None,
                name.get_text(strip=True) if name else None
            ])
        )
        if ingredient_text:
            ingredients.append(ingredient_text)

    # --- INSTRUCTIONS ---
    instructions = []
    for idx, li in enumerate(soup.find_all("li", class_="wprm-recipe-instruction"), start=1):
        step = li.find("div", class_="wprm-recipe-instruction-text")
        if step:
            step_text = step.get_text(" ", strip=True)  # preserve spaces in <span>/<div>
            instructions.append(f"Step {idx}: {step_text}")

    return {
        "ingredients": ingredients,
        "instructions": instructions
    }

conversation_context = None  # global or stored per-session

def query_ollama(prompt, model=DEFAULT_MODEL, system_text=None): # chatGPT generated
    """Query Ollama and return response with conversation memory support"""
    global conversation_context
    
    try:
        payload = {
            "model": model,
            "prompt": prompt,
            "stream": False
        }

        # Add system instruction if provided
        if system_text:
            payload["system"] = system_text

        # Add prior conversation context if it exists
        if conversation_context:
            payload["context"] = conversation_context

        response = requests.post(
            f"{OLLAMA_URL}/api/generate",
            json=payload,
            timeout=40
        )

        if response.status_code == 200:
            data = response.json()
            # Save context for future turns
            if "context" in data:
                conversation_context = data["context"]
            return data.get("response", "No response generated")
        else:
            return f"Error: Ollama returned status {response.status_code}"
    
    except requests.exceptions.Timeout:
        return "Sorry, the response took too long. Please try again."
    except Exception as e:
        return f"Error: {str(e)}"


def speak_text(text):
    """Simple text-to-speech using espeak"""
    # Clean text to avoid encoding issues
    clean_text = text.encode('ascii', 'ignore').decode('ascii')
    print(f"Assistant: {clean_text}")
    time.sleep(0.4)
    subprocess.run(['espeak', f'"{clean_text}"'], check=False)
    # this was debugged with chatGPT

