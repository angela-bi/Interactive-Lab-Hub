@app.route('/api/chat', methods=['POST'])
def chat_api():
    """REST API endpoint for chat"""
    data = request.get_json()
    user_message = data.get('message', '')
    
    if not user_message:
        return jsonify({'error': 'No message provided'}), 400
    
    # Query Ollama
    response = query_ollama(user_message)
    
    return jsonify({
        'user_message': user_message,
        'ai_response': response
    })

@socketio.on('chat_message')
def handle_chat_message(data):
    """Handle chat message via WebSocket"""
    user_message = data.get('message', '')

    if user_message:
        # If it looks like a recipe link, scrape it
        if user_message.startswith("http://") or user_message.startswith("https://"):
            try:
                recipe = get_recipe_from_url(user_message)
                recipe_text = (
                    "📝 Ingredients:\n- " + "\n- ".join(recipe["ingredients"]) +
                    "\n\n👩‍🍳 Instructions:\n" + "\n".join(recipe["instructions"])
                )
                full_prompt = (
                    f"Here is the recipe that you're tasked with answering questions about:\n{recipe_text}\n\n"
                    "You are a helpful baking assistant offering to help with the recipe. Don't use emojis, only use plain text without astericks, and keep responses brief."
                )
                ai_response = query_ollama("Hi, who are you?", system_text=full_prompt) # manually edited
            except Exception as e:
                ai_response = f"⚠️ Sorry, I couldn’t parse that recipe link. Error: {str(e)}"
        else:
            # Otherwise, send message to Ollama
            ai_response = query_ollama(user_message)


        # Send response back to client
        emit('ai_response', {
            'user_message': user_message,
            'ai_response': ai_response
        })

